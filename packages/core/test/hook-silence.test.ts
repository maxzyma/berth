import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { installHooks } from '../src/agents/hooks.js';
import { lastClaudePrompt, promptTopic } from '../src/agents/hook-silence.js';
import { list } from '../src/registry/sessions.js';
import { sandbox, CLI } from './helpers.js';

// Synthetic transcript records in Claude Code's JSONL shape (spec §4.2).
const user = (content: unknown, timestamp: string) => JSON.stringify({ type: 'user', timestamp, origin: { kind: 'human' }, message: { role: 'user', content } });
const assistant = (timestamp: string) => JSON.stringify({ type: 'assistant', timestamp, message: { role: 'assistant', content: [{ type: 'text', text: 'ok' }] } });

test('promptTopic is the subtitle a prompt hook reports: first real line, placeholders and agent text dropped', () => {
  assert.equal(promptTopic('  Fix the   build\nthen run tests'), 'Fix the build');
  assert.equal(promptTopic('[Image #3]\nWhat is this?'), 'What is this?');
  assert.equal(promptTopic('<command-name>/hooks</command-name>'), undefined);
  assert.equal(promptTopic('[Pasted text #1 +20 lines]'), undefined);
  assert.equal(promptTopic('x'.repeat(200))?.length, 120);
});

test('lastClaudePrompt returns the latest prompt a person typed, skipping tool results, summaries, sidechains, other sessions and agent-injected text', (t) => {
  const sb = sandbox(t);
  const file = join(sb.root, 'conversation.jsonl');
  writeFileSync(file, [
    user('First question', '2026-11-18T10:00:00.000Z'),
    assistant('2026-11-18T10:00:05.000Z'),
    user('Second question\nwith detail', '2026-11-18T10:10:00.000Z'),
    user([{ type: 'tool_result', content: 'output' }], '2026-11-18T10:10:30.000Z'),
    user('<task-notification>done</task-notification>', '2026-11-18T10:11:00.000Z'),
    JSON.stringify({ type: 'user', timestamp: '2026-11-18T10:12:00.000Z', isCompactSummary: true, isVisibleInTranscriptOnly: true, message: { role: 'user', content: 'This session is being continued from a previous conversation.' } }),
    JSON.stringify({ type: 'user', timestamp: '2026-11-18T10:13:00.000Z', isSidechain: true, message: { role: 'user', content: 'A subagent task' } }),
    JSON.stringify({ type: 'user', timestamp: '2026-11-18T10:14:00.000Z', isMeta: true, message: { role: 'user', content: 'Caveat: generated by the agent' } }),
    JSON.stringify({ type: 'user', timestamp: '2026-11-18T10:15:00.000Z', message: { role: 'user', content: 'Another Claude session sent a message:\nreport' } }),
    assistant('2026-11-18T10:11:05.000Z'),
    '{"type":"user","timestamp":', // an incomplete last record
  ].join('\n'));
  assert.deepEqual(lastClaudePrompt(file), { at: '2026-11-18T10:10:00.000Z', topic: 'Second question' });
  // A message sent while the agent works is recorded as a queued command, and prompt hooks report it.
  writeFileSync(file, `${user('Main question', '2026-11-18T11:00:00.000Z')}\n${JSON.stringify({ type: 'attachment', timestamp: '2026-11-18T11:00:30.000Z', attachment: { type: 'queued_command', prompt: 'Queued follow-up\nmore', commandMode: 'prompt', origin: { kind: 'human' } } })}\n`);
  assert.deepEqual(lastClaudePrompt(file), { at: '2026-11-18T11:00:30.000Z', topic: 'Queued follow-up' });
  assert.equal(lastClaudePrompt(join(sb.root, 'absent.jsonl')), undefined);
});

test('a live Claude session whose transcript has an unreported prompt carries hooksSilent', (t) => {
  const sb = sandbox(t);
  const home = sb.env.HOME!;
  installHooks('claude', CLI, { HOME: home });
  const cwd = sb.makeDir('work');
  assert.equal(sb.cli('new', 'claude', '--cwd', cwd, '--name', 'work').status, 0);
  const id = '0f0e0d0c-0b0a-4908-8706-050403020100';
  const ctx = sb.ctx();
  ctx.tmux.setMeta('work', { conversation: id, topic: 'Earlier question', profile: JSON.stringify({ environment: { HOME: home } }) });
  const dir = join(home, '.claude', 'projects', cwd.replace(/[^A-Za-z0-9]/g, '-'));
  mkdirSync(dir, { recursive: true });
  const transcript = (prompt: string, minutesAgo: number) => writeFileSync(join(dir, `${id}.jsonl`),
    `${user(prompt, new Date(Date.now() - minutesAgo * 60_000).toISOString())}\n`);
  const work = () => list(ctx).find((row) => row.name === 'work');

  transcript('Newer question', 10);
  assert.equal(work()?.hooksSilent, true, 'a prompt the hooks never reported');
  transcript('Newer question', 0.5);
  assert.equal(work()?.hooksSilent, undefined, 'a recent prompt may still be on its way');
  const two = (older: string, olderAgo: number, newer: string, newerAgo: number) => writeFileSync(join(dir, `${id}.jsonl`),
    `${user(older, new Date(Date.now() - olderAgo * 60_000).toISOString())}\n${user(newer, new Date(Date.now() - newerAgo * 60_000).toISOString())}\n`);
  two('Unreported question', 10, 'Just sent', 0.5);
  assert.equal(work()?.hooksSilent, true, 'a new prompt does not hide an earlier unreported one');
  two('Earlier question', 10, 'Just sent', 0.5);
  assert.equal(work()?.hooksSilent, undefined, 'the hooks reported the prompt before the one just sent');
  transcript('Earlier question', 10);
  assert.equal(work()?.hooksSilent, undefined, 'the hooks reported the latest prompt');
});
