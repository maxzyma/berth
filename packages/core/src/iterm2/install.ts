import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import type { Context } from '../context.js';
import { BerthError, ExitCode } from '../errors.js';
import { ensure } from '../restore/ensure.js';
import { renderTemplate, shellQuote } from '../shell.js';
import { PANE_VARIABLE } from '../present/attach.js';

/**
 * Berth for iTerm2 (spec §7): iTerm2 restores windows, tabs and split panes;
 * an AutoLaunch script puts each restored pane back in its session. iTerm2
 * starts AutoLaunch scripts with a minimal PATH, so every tool is referenced
 * by absolute path.
 */

export interface Iterm2Paths {
  script: string;
  /** Written by earlier versions (one profile per session); removed on install. */
  legacyProfiles: string;
}

export function iterm2Paths(env = process.env): Iterm2Paths {
  const base = join(env.HOME || homedir(), 'Library', 'Application Support', 'iTerm2');
  return {
    script: join(base, 'Scripts', 'AutoLaunch', 'berth.py'),
    legacyProfiles: join(base, 'DynamicProfiles', 'berth.json'),
  };
}

export interface Tools {
  node: string;
  cli: string;
  tmux: string;
  socket?: string;
  /** PATH at install time: AutoLaunch scripts get a minimal one, without tmux or the agents. */
  path?: string;
}

/** Command that attaches a pane to `session`: the configured template, or tmux attach. */
export function attachCommand(ctx: Context, tools: Tools, session: string): string {
  const template = ctx.config.iterm2Attach;
  if (template) return renderTemplate(template, { session });
  const socket = tools.socket ? ` -L ${shellQuote(tools.socket)}` : '';
  return `${shellQuote(tools.tmux)}${socket} attach-session -t ${shellQuote(`=${session}`)}`;
}

/** `berth iterm2 reattach <session>`: rebuild the session if missing, return its attach command. */
export function reattach(ctx: Context, tools: Tools, session: string): string {
  if (!ctx.tmux.hasSession(session)) ensure(ctx, { session });
  if (!ctx.tmux.hasSession(session)) throw new BerthError(`cannot restore session ${session}`, ExitCode.notFound);
  return attachCommand(ctx, tools, session);
}

export function autoLaunchScript(tools: Tools): string {
  const berth = JSON.stringify([tools.node, tools.cli, ...(tools.socket ? ['--socket', tools.socket] : [])]);
  return `#!/usr/bin/env python3
"""Berth for iTerm2: put each pane iTerm2 restored back in its agent session.

Generated by \`berth iterm2 install\`; do not edit. iTerm2 restores the
windows, tabs and split panes; Berth marked each pane with the session it
showed (user variable ${PANE_VARIABLE}). This script asks the berth CLI to
rebuild a missing session and to give the command that attaches it, and
types that command into the pane. It holds no session logic.
"""
import asyncio
import os
import subprocess

import iterm2

BERTH = ${berth}
VARIABLE = "user.${PANE_VARIABLE}"
# Recorded at install: iTerm2's PATH for AutoLaunch has neither tmux nor the agent CLIs.
ENV = dict(os.environ, PATH=${JSON.stringify(tools.path ?? '')} or os.environ.get("PATH", ""))


def attach_command(session_name):
    try:
        done = subprocess.run(BERTH + ["iterm2", "reattach", session_name], capture_output=True, text=True, timeout=120, env=ENV)
    except (OSError, subprocess.SubprocessError):
        return None
    command = done.stdout.strip()
    return command if done.returncode == 0 and command else None


async def panes(app):
    for window in app.terminal_windows:
        for tab in window.tabs:
            for session in tab.sessions:
                yield session


async def main(connection):
    app = await iterm2.async_get_app(connection)
    # Window restoration may still be running when AutoLaunch starts.
    for _ in range(20):
        if app.terminal_windows:
            break
        await asyncio.sleep(0.5)
    await asyncio.sleep(1)
    async for session in panes(app):
        name = await session.async_get_variable(VARIABLE)
        if not name:
            continue
        job = await session.async_get_variable("jobName")
        if job == "tmux":
            continue  # still attached (iTerm2 kept the process alive)
        command = await asyncio.get_running_loop().run_in_executor(None, attach_command, name)
        if command:
            await session.async_send_text(command + "\\n")
        else:
            # Shown on the screen only, never run by the shell.
            await session.async_inject(("berth: could not restore session %s\\r\\n" % name).encode())


iterm2.run_until_complete(main)
`;
}

export function installIterm2(tools: Tools, env = process.env): Iterm2Paths {
  const paths = iterm2Paths(env);
  mkdirSync(dirname(paths.script), { recursive: true });
  writeFileSync(paths.script, autoLaunchScript(tools), { mode: 0o755 });
  rmSync(paths.legacyProfiles, { force: true });
  return paths;
}

export function uninstallIterm2(env = process.env): Iterm2Paths {
  const paths = iterm2Paths(env);
  rmSync(paths.script, { force: true });
  rmSync(paths.legacyProfiles, { force: true });
  return paths;
}

export function iterm2Installed(env = process.env): boolean {
  return existsSync(iterm2Paths(env).script);
}
