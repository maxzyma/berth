import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import type { Context } from '../context.js';
import { shellQuote } from '../shell.js';
import { list } from '../registry/sessions.js';

/**
 * Berth for iTerm2 (spec §7): an AutoLaunch script plus one dynamic profile per
 * `iterm2`-origin session. iTerm2 starts AutoLaunch scripts with a minimal
 * PATH, so every tool is referenced by absolute path.
 */

export interface Iterm2Paths {
  script: string;
  profiles: string;
}

export function iterm2Paths(env = process.env): Iterm2Paths {
  const base = join(env.HOME || homedir(), 'Library', 'Application Support', 'iTerm2');
  return {
    script: join(base, 'Scripts', 'AutoLaunch', 'berth.py'),
    profiles: join(base, 'DynamicProfiles', 'berth.json'),
  };
}

export interface Tools {
  node: string;
  cli: string;
  tmux: string;
  socket?: string;
}

function tmuxArgs(tools: Tools): string {
  return [shellQuote(tools.tmux), ...(tools.socket ? ['-L', shellQuote(tools.socket)] : [])].join(' ');
}

/** attach; if the session is missing, rebuild it (once, under the core's lock), then attach. */
export function attachOrHeal(tools: Tools, session: string): string {
  const tmux = tmuxArgs(tools);
  const target = shellQuote(`=${session}`);
  const berth = `${shellQuote(tools.node)} ${shellQuote(tools.cli)}`;
  const socket = tools.socket ? ` --socket ${shellQuote(tools.socket)}` : '';
  return `${tmux} attach-session -t ${target} 2>/dev/null || { ${berth}${socket} ensure --origin iterm2 ${shellQuote(session)} >/dev/null; ${tmux} attach-session -t ${target}; }`;
}

export function profileGuid(session: string): string {
  return `berth-${session}`;
}

export function profilesJson(tools: Tools, sessions: { name: string; cwd: string }[]): string {
  const profiles = sessions.map((s) => ({
    Name: `Berth: ${s.name}`,
    Guid: profileGuid(s.name),
    'Custom Command': 'Yes',
    Command: `/bin/sh -c ${shellQuote(attachOrHeal(tools, s.name))}`,
    'Custom Directory': 'Yes',
    'Working Directory': s.cwd,
    Tags: ['berth'],
  }));
  return `${JSON.stringify({ Profiles: profiles }, null, 2)}\n`;
}

export function autoLaunchScript(tools: Tools): string {
  const berth = JSON.stringify([tools.node, tools.cli, ...(tools.socket ? ['--socket', tools.socket] : [])]);
  return `#!/usr/bin/env python3
"""Berth for iTerm2: reopen this terminal's agent sessions at startup.

Generated by \`berth iterm2 install\`; do not edit. Holds no session logic: the
berth CLI decides which sessions belong to iTerm2 and rebuilds missing ones.
"""
import asyncio
import json
import subprocess

import iterm2

BERTH = ${berth}


def iterm2_sessions():
    try:
        out = subprocess.run(BERTH + ["ls", "--json"], capture_output=True, text=True, timeout=30).stdout
        rows = json.loads(out or "[]")
    except (OSError, ValueError, subprocess.SubprocessError):
        return []
    # A session some terminal already shows is left alone.
    return [r for r in rows if r.get("managed") and r.get("origin") == "iterm2" and not r.get("attachedClients")]


async def main(connection):
    app = await iterm2.async_get_app(connection)
    window = app.current_terminal_window
    for row in iterm2_sessions():
        profile = "Berth: " + row["name"]
        if window is None:
            window = await iterm2.Window.async_create(connection, profile=profile)
        else:
            await window.async_create_tab(profile=profile)


iterm2.run_until_complete(main)
`;
}

export function writeProfiles(ctx: Context, tools: Tools, env = process.env): string {
  const { profiles } = iterm2Paths(env);
  const sessions = list(ctx).filter((r) => r.managed && r.origin === 'iterm2').map((r) => ({ name: r.name, cwd: r.cwd }));
  mkdirSync(dirname(profiles), { recursive: true });
  writeFileSync(profiles, profilesJson(tools, sessions));
  return profiles;
}

export function installIterm2(ctx: Context, tools: Tools, env = process.env): Iterm2Paths {
  const paths = iterm2Paths(env);
  mkdirSync(dirname(paths.script), { recursive: true });
  writeFileSync(paths.script, autoLaunchScript(tools), { mode: 0o755 });
  writeProfiles(ctx, tools, env);
  return paths;
}

export function uninstallIterm2(env = process.env): Iterm2Paths {
  const paths = iterm2Paths(env);
  rmSync(paths.script, { force: true });
  rmSync(paths.profiles, { force: true });
  return paths;
}

/** Keep profiles in step with sessions once the iTerm2 frontend is installed. */
export function refreshIterm2IfInstalled(ctx: Context, tools: Tools, env = process.env): void {
  if (existsSync(iterm2Paths(env).profiles)) writeProfiles(ctx, tools, env);
}
